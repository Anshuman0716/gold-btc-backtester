"""
Reproducible benchmark — fixed-date backtests on committed data fixtures.

Every number this script prints comes from parquet files committed under
tests/fixtures/, never from a live download, so re-running it on any date
gives identical results. The output contains no timestamps for the same reason.

Usage:
    python scripts/benchmark.py                  # run, write results/benchmark.md
    python scripts/benchmark.py --update-readme  # also refresh the README block
    python scripts/benchmark.py --refresh-fixtures
        # one-off: re-download the fixtures from yfinance (changes the data,
        # so commit the new files and the new results together)
"""

import argparse
import hashlib
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import pandas as pd

from analytics.tearsheet import compute_tearsheet, format_ratio
from risk.controls import RiskParams, apply_risk_controls
from strategy.ema_crossover import EMACrossover
from strategy.donchian import DonchianBreakout
from strategy.momentum import TimeSeriesMomentum
from strategy.mean_reversion import BollingerMeanReversion

# --- Pinned configuration (change these and the results change) ---
START = "2022-01-01"
END = "2024-12-31"            # inclusive last bar
INTERVAL = "1d"
SYMBOLS = ["BTC-USD", "GC=F"]
STRATEGIES = [
    EMACrossover(fast_period=9, slow_period=21),
    EMACrossover(fast_period=20, slow_period=50),
    DonchianBreakout(channel_period=20),
    TimeSeriesMomentum(lookback=50),
    BollingerMeanReversion(),
]
RISK = RiskParams(
    initial_capital=100_000,
    risk_per_trade=0.01,
    atr_period=14,
    stop_loss_atr=2.0,
    take_profit_atr=3.0,
    max_drawdown_pct=0.20,
    commission_bps=10,
    slippage_bps=5,
)

FIXTURE_DIR = ROOT / "tests" / "fixtures"
RESULTS_PATH = ROOT / "results" / "benchmark.md"
README_PATH = ROOT / "README.md"
README_START = "<!-- BENCHMARK:START -->"
README_END = "<!-- BENCHMARK:END -->"


def fixture_path(symbol: str) -> Path:
    safe = symbol.replace("=", "_").replace("-", "_")
    return FIXTURE_DIR / f"{safe}_{INTERVAL}_{START}_{END}.parquet"


def refresh_fixtures() -> None:
    """Download the pinned window from yfinance and overwrite the fixtures."""
    from data.yfinance_source import YFinanceSource

    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    source = YFinanceSource()
    # yfinance treats `end` as exclusive, so ask for one day past END.
    end_exclusive = pd.Timestamp(END) + pd.Timedelta(days=1)
    for symbol in SYMBOLS:
        df = source.fetch_ohlcv(
            symbol, INTERVAL, datetime.fromisoformat(START), end_exclusive.to_pydatetime()
        )
        df = df.loc[:END]
        df.to_parquet(fixture_path(symbol))
        print(f"  wrote {fixture_path(symbol).relative_to(ROOT)} ({len(df)} bars)")


def load_fixture(symbol: str) -> pd.DataFrame:
    path = fixture_path(symbol)
    if not path.exists():
        sys.exit(
            f"Missing fixture {path.relative_to(ROOT)}. "
            "Run with --refresh-fixtures once and commit the result."
        )
    return pd.read_parquet(path)


def sha256_short(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def run() -> str:
    rows = []
    data_rows = []
    for symbol in SYMBOLS:
        df = load_fixture(symbol)
        buy_hold = df["close"].iloc[-1] / df["close"].iloc[0] - 1
        data_rows.append(
            f"| {symbol} | {df.index[0].date()} | {df.index[-1].date()} | {len(df)} "
            f"| `{fixture_path(symbol).name}` | `{sha256_short(fixture_path(symbol))}` |"
        )
        for strat in STRATEGIES:
            signals = strat.generate_signals(df)
            trades, equity = apply_risk_controls(signals, df, RISK)
            ts = compute_tearsheet(
                trades=trades,
                equity_curve=equity,
                initial_capital=RISK.initial_capital,
                asset=symbol,
                interval=INTERVAL,
            )
            params = ", ".join(f"{k}={v}" for k, v in strat.get_params().items())
            rows.append(
                f"| {symbol} | {strat.name} ({params}) "
                f"| {ts.total_return * 100:.2f}% | {buy_hold * 100:.2f}% "
                f"| {format_ratio(ts.sharpe_ratio)} | {format_ratio(ts.sortino_ratio)} "
                f"| {ts.max_drawdown * 100:.2f}% | {ts.win_rate * 100:.1f}% "
                f"| {format_ratio(ts.profit_factor)} | {ts.num_trades} |"
            )

    lines = [
        f"Fixed window **{START} to {END}**, {INTERVAL} bars, data from committed fixtures "
        f"(`tests/fixtures/`). Generated by `python scripts/benchmark.py`.",
        "",
        f"Risk: capital ${RISK.initial_capital:,.0f}, risk/trade {RISK.risk_per_trade:.0%}, "
        f"ATR({RISK.atr_period}) SL {RISK.stop_loss_atr}x / TP {RISK.take_profit_atr}x, "
        f"kill-switch at {RISK.max_drawdown_pct:.0%} drawdown, "
        f"costs {RISK.commission_bps:.0f} bps commission + {RISK.slippage_bps:.0f} bps slippage per side. "
        "Results are in-sample single-window backtests; see `results/walkforward.md` for out-of-sample.",
        "",
        "| Asset | Strategy | Return | Buy & Hold | Sharpe | Sortino | Max DD | Win Rate | Profit Factor | Trades |",
        "|---|---|---|---|---|---|---|---|---|---|",
        *rows,
        "",
        "| Asset | First bar | Last bar | Bars | Fixture | SHA-256 (12) |",
        "|---|---|---|---|---|---|",
        *data_rows,
    ]
    return "\n".join(lines) + "\n"


def update_readme(table: str) -> None:
    text = README_PATH.read_text(encoding="utf-8")
    if README_START not in text or README_END not in text:
        sys.exit(f"README is missing the {README_START} / {README_END} markers.")
    head, rest = text.split(README_START, 1)
    _, tail = rest.split(README_END, 1)
    README_PATH.write_text(
        f"{head}{README_START}\n{table}{README_END}{tail}", encoding="utf-8", newline="\n"
    )
    print(f"  updated {README_PATH.relative_to(ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    parser.add_argument("--refresh-fixtures", action="store_true",
                        help="re-download fixtures from yfinance (network)")
    parser.add_argument("--update-readme", action="store_true",
                        help="replace the benchmark block in README.md")
    args = parser.parse_args()

    if args.refresh_fixtures:
        refresh_fixtures()

    table = run()
    RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_PATH.write_text("# Benchmark results\n\n" + table, encoding="utf-8", newline="\n")
    print(table)
    print(f"  wrote {RESULTS_PATH.relative_to(ROOT)}")

    if args.update_readme:
        update_readme(table)


if __name__ == "__main__":
    main()
